export function sectionForLesson(number: number): LessonSection {
  if (number <= 6) return 1;
  if (number <= 13) return 2;
  if (number <= 18) return 3;
  return 4;
}

export function waveForLesson(number: number): number {
  return sectionForLesson(number) - 1;
}

