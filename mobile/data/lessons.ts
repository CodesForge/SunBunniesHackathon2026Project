export type LessonSection = 1 | 2 | 3 | 4;

export type QuestionDifficulty = "recognition" | "application" | "transfer";

export type LessonQuestion = {
  id: string;
  difficulty: QuestionDifficulty;
  prompt: string;
  options: string[];
  correctIndex?: number;
  correctIndexes?: number[];
  anyCorrect?: boolean;
  explanation: string;
  optionsCoinsDelta?: number[];
  dynamic?: "topCategory" | "planVsActual";
};

export type SortCard = { id: string; text: string; basket: "a" | "b" };

export type SortStepData = {
  kind: "sort";
  basketA: string;
  basketB: string;
  cards: SortCard[];
  explanation: string;
};

export type BasketItemData = {
  id: string;
  title: string;
  price: number;
  required: boolean;
};

export type BasketStepData = {
  kind: "basket";
  budget: number;
  items: BasketItemData[];
  explanation: string;
};

export type QuestionsStepData = {
  kind: "questions";
  questions: LessonQuestion[];
};

export type PlanStepData = { kind: "plan" };

export type LessonStep =
  | SortStepData
  | BasketStepData
  | QuestionsStepData
  | PlanStepData;

export type Lesson = {
  id: string;
  number: number;
  section: LessonSection;
  title: string;
  themeLabel: string;
  objective: string;
  story: string[];
  steps: LessonStep[];
  reward: number;
};

